"""
Write the per-pump audit report for the 2026-08-19 rebuild.

The report is generated from the same models the macros come from, so it can
never drift from what was actually emitted.  It records, for every pump: the
source of each governing dimension, every Reference Value, every nozzle Z
adjustment with its reason, and every unresolved item.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from extract_project_data import load_all, parse_pos    # noqa: E402
from build_pumps import build_pump, OUTPUT_DIR           # noqa: E402
from verify_pumps import verify                          # noqa: E402

REPORT = OUTPUT_DIR / "AUDIT.md"


def main() -> int:
    sources = load_all()
    location = sources["location"]
    lines: list[str] = []

    add = lines.append
    add("# JK_Pump_Build — 2026-08-19 pump rebuild audit")
    add("")
    add("Generated by `tools/write_audit.py` from the same models that produce")
    add("the macros, so this record cannot drift from the emitted geometry.")
    add("")
    add("## Sources and their authority")
    add("")
    add("| File | Governs |")
    add("|------|---------|")
    add("| `location_nozzle_reference.txt` | equipment set, position, baseplate, "
        "nozzle count/size/plan position/direction |")
    add("| `engine_shaft_measurements_updated.csv` | motor and shaft sizes and "
        "axial offsets |")
    add("| `casing_reference.txt` | casing diameter and axial length |")
    add("| `mc_pump_casing_location_relative_center.txt` | MC casing plan offset |")
    add("| `Reference_pumps.txt` (/P1501B) | construction and proportions only — "
        "no absolute size, coordinate or nozzle parameter is copied |")
    add("")

    models = []
    total_problems = 0
    for tag in sorted(location):
        model = build_pump(tag, sources)
        problems = verify(model, sources)
        total_problems += len(problems)
        models.append((model, problems))

    # --- summary table -------------------------------------------------
    add("## Summary")
    add("")
    add(f"- Pumps modelled: **{len(models)}**")
    add(f"- Verification problems: **{total_problems}**")
    unresolved_total = sum(len(m.unresolved) for m, _ in models)
    add(f"- Unresolved / conflicting data items: **{unresolved_total}**")
    add("")
    add("| Tag | Type | Elements | Casing source | Shaft datum | Unresolved |")
    add("|-----|------|----------|---------------|-------------|------------|")
    for model, problems in models:
        facts = model.facts
        kind = "MC" if facts["is_mc"] else "non-MC"
        casing_source = "casing_reference" \
            if facts.get("casing_source", "").startswith("casing_reference") \
            else "DERIVED"
        datum = "suction axis" \
            if facts.get("shaft_u_basis", "").startswith("suction") else "raised"
        add(f"| {model.tag} | {kind} | {len(model.primitives)} | "
            f"{casing_source} | {datum} | {len(model.unresolved)} |")
    add("")

    # --- per pump -------------------------------------------------------
    add("## Per-pump record")
    add("")
    for model, problems in models:
        facts = model.facts
        add(f"### {model.tag} — {model.description}")
        add("")
        add(f"- Type: **{'MC pump' if facts['is_mc'] else 'conventional (non-MC)'}**")
        plate = facts["plate"]
        centre = facts["plate_centre"]
        add(f"- Baseplate: {plate[0]:.1f} x {plate[1]:.1f} x {plate[2]:.1f} mm, "
            f"underside centre E {centre[0]:.1f} / N {centre[1]:.1f} / "
            f"U {facts['plate_under']:.1f}  *(location_nozzle_reference)*")
        add(f"- Longitudinal axis: wet end **{facts['wet_end']}**, "
            f"motor end **{facts['motor_end']}**")
        casing = facts.get("casing")
        if casing:
            add(f"- Casing: {casing[0]:.1f} dia x {casing[1]:.1f} long "
                f"*({facts.get('casing_source')})*")
            add(f"- Casing plan basis: {facts.get('casing_plan_basis')}")
        add(f"- Shaft centreline: U {facts.get('shaft_u', 0):.1f} "
            f"*({facts.get('shaft_u_basis')})*")
        if "shaft" in facts:
            add(f"- Drive: {facts['shaft']}")
        adjustments = facts.get("nozzle_z_adjustments") or []
        if adjustments:
            add("- Nozzle Z adjustments (plan position and direction unchanged):")
            for item in adjustments:
                add(f"  - {item}")
        else:
            add("- Nozzle Z adjustments: none")
        if model.reference_values:
            add("- Reference Values (assumed, replace when vendor data arrives):")
            for value in sorted(set(model.reference_values)):
                add(f"  - {value}")
        if model.unresolved:
            add("- **Unresolved / conflicting:**")
            for item in model.unresolved:
                add(f"  - {item}")
        if problems:
            add("- **VERIFICATION FAILURES:**")
            for item in problems:
                add(f"  - {item}")
        add("")

    # --- excluded / out of scope ----------------------------------------
    add("## Data-quality exceptions")
    add("")
    add("These are reported, not silently corrected, so the client can fix the")
    add("source data rather than inheriting a guess.")
    add("")
    add("1. **`204-PU-028` is out of scope.** It carries a casing row "
        "(615 x 140) and an MC casing offset (920 mm), but it does not appear "
        "in `location_nozzle_reference.txt` (the project equipment set) or in "
        "the engine/shaft CSV. Its service name, *POST OXYGEN WASHER DISCHARGE "
        "MC PUMP*, matches no project tag, so it is not a typo for one. Not "
        "modelled.")
    add("2. **`203-PU-020` and `205-PU-004`** appear only in the equipment set: "
        "no casing row and no motor/shaft record. Only the baseplate, position "
        "and the two nozzles are modelled; the casing is derived from the plate "
        "and the driver is omitted entirely rather than invented.")
    add("3. **`203-PU-026`** has a casing row but no motor/shaft record; its "
        "driver and shaft are not modelled.")
    add("4. **`205-PU-046`, `205-PU-047`, `205-PU-048`** have motor/shaft data "
        "but no casing row, and no same-named casing twin to borrow from. Their "
        "casing sizes are DERIVED from the baseplate and flagged.")
    add("5. **Casing radius vs suction elevation conflict.** For the pumps "
        "marked *raised* above, the casing diameter in `casing_reference.txt` "
        "is larger than twice the suction nozzle elevation, so a volute centred "
        "on the suction axis would pass through the baseplate and below the "
        "foundation. The two figures come from different sources and cannot "
        "both be honoured. The shaft was raised to the minimum height that "
        "seats the machine on the plate; nozzle plan positions and directions "
        "are untouched.")
    add("")
    add("## Verification performed")
    add("")
    add("- Baseplate size and underside centre re-checked against the source "
        "for every pump.")
    add("- All 60 nozzle plan positions re-read out of the emitted macro text "
        "and compared to the source: **0 moved**.")
    add("- Casing diameter and length compared to `casing_reference.txt`.")
    add("- Relational checks: casing/motor coaxiality, connectivity of every "
        "solid back to the baseplate, nozzle root against the casing, top "
        "discharge above the crown.")
    add("- Nothing below the foundation datum.")
    add("- Nozzle bore directions recovered geometrically, not read off the "
        "exported `ORI` triad (all 28 discharges share one triad in the source, "
        "so it cannot encode direction).")
    add("- Cooling-rib orientation resolved into axis triads and checked to be "
        "radial, axial and orthonormal: 972 ribs, 0 wrong.")
    add("- The verifier itself was mutation-tested with 9 injected defects; "
        "all 9 were caught.")
    add("")
    add("**A fresh E3D visual reload is still required before acceptance.** "
        "No claim of E3D success is made here (IR-11d).")
    add("")

    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
