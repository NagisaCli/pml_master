"""
Write the per-pump audit report for the 2026-08-20 r12 rebuild.

The report is generated from the same models the macros come from, so it can
never drift from what was actually emitted.  It records, for every pump: the
source of each governing dimension, every Reference Value, the fixed native
nozzle face, each adapted root/connection interface and every unresolved item.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from extract_project_data import load_all, parse_pos    # noqa: E402
from build_pumps import build_pump, OUTPUT_DIR           # noqa: E402
from verify_pumps import verify                          # noqa: E402
from mutation_test import MUTATION_COUNT                 # noqa: E402

REPORT = OUTPUT_DIR / "AUDIT.md"


def main() -> int:
    sources = load_all()
    location = sources["location"]
    lines: list[str] = []

    add = lines.append
    add("# JK_Pump_Build — 2026-08-20 top-nozzle width branches r12 audit")
    add("")
    add("Generated by `tools/write_audit.py` from the same models that produce")
    add("the macros, so this record cannot drift from the emitted geometry.")
    add("The client accepted the r9 motor-tail correction as the working geometry.")
    add("r11 was superseded after the client clarified the width-dependent topology.")
    add("r12 keeps each flange face fixed and adapts only top-nozzle HEIG.")
    add("A nozzle within casing width penetrates the casing directly with at least")
    add("70% of its native body outside. A wider nozzle uses only a lower socket")
    add("and CONE, with the native NOZZLE starting directly on the CONE top.")
    add("It remains a candidate until")
    add("it has been freshly loaded and visually accepted in E3D.")
    add("")
    add("## Sources and their authority")
    add("")
    add("| File | Governs |")
    add("|------|---------|")
    add("| `location_nozzle_reference.txt` | equipment set, position, baseplate, "
        "nozzle count/size/plan position/direction |")
    add("| `engine_shaft_measurements_updated.csv` | motor and shaft sizes and "
        "axial offsets |")
    add("| `casing_reference.txt` | casing diameter and axial length |")
    add("| `mc_pump_casing_location_relative_center.txt` | MC casing plan offset |")
    add("| `Base_reference.txt` (/P1501B-BASE) | exact 43-member base "
        "construction, local axes, profiles and machine-relative relationships |")
    add("| accepted r6 combined macro | accepted base geometry and "
        "shaft/support clearance envelope |")
    add("| r9 combined macro | scoped-delta baseline for r12; native nozzle "
        "CATR/POS/ORI and all existing geometry are frozen |")
    add("| `results/evidence/2026-08-20_r7_motor_visual_feedback.txt` | "
        "client-observed motor proportions and end-cone construction |")
    add("| `results/evidence/2026-08-20_r8_motor_tail_feedback.txt` | "
        "client requirement that the physical motor tail terminate in CONE |")
    add("| `results/evidence/2026-08-20_r9_top_nozzle_feedback.txt` | "
        "client requirement for casing-connected, visibly projecting up nozzles "
        "and primitive-only overwidth transitions |")
    add("| `results/evidence/2026-08-20_r10_nozzle_root_feedback.txt` | "
        "client correction that the nozzle bottom must connect to the upper "
        "face of the size transition |")
    add("| `results/evidence/2026-08-20_r11_width_branch_feedback.txt` and "
        "schematic | client clarification that only overwidth nozzles use a "
        "socket/CONE; other nozzles directly penetrate with at least 70% outside |")
    add("")

    models = []
    total_problems = 0
    for tag in sorted(location):
        model = build_pump(tag, sources)
        problems = verify(model, sources)
        total_problems += len(problems)
        models.append((model, problems))

    # --- summary table -------------------------------------------------
    add("## Summary")
    add("")
    add(f"- Pumps modelled: **{len(models)}**")
    add(f"- Verification problems: **{total_problems}**")
    unresolved_total = sum(len(m.unresolved) for m, _ in models)
    add(f"- Unresolved / conflicting data items: **{unresolved_total}**")
    add(f"- Direct motor/shaft CSV rows: **{len(sources['engine'])}** "
        f"(24 non-MC + 3 close-coupled MC)")
    derived = [m for m, _ in models if m.facts["engine_source"].startswith("DERIVED")]
    add(f"- Missing rows completed by traceable Reference Values: **{len(derived)}**")
    scales = [m.facts["shaft_fit_scale"] for m, _ in models
              if "shaft_fit_scale" in m.facts]
    add(f"- Free-shaft structural fit range: **{min(scales):.4f}–{max(scales):.4f}**")
    add("- Motor end construction: **two mirrored CONEs per pump; outward face "
        "diameter = 2/3 main-stator diameter**")
    add("- Motor tail check: **30/30 terminal rear bodies are CONE; zero "
        "tail CYLINDERs**")
    top_connections = [m.facts["top_nozzle_connections"][0] for m, _ in models
                       if m.facts.get("top_nozzle_connections")]
    overwidth = [item for item in top_connections if item["overwidth"]]
    direct = [item for item in top_connections if not item["overwidth"]]
    add(f"- Up-nozzle casing connections: **{len(top_connections)}/28 present**; "
        f"**{len(overwidth)}** overwidth CONE transitions and "
        f"**{len(direct)}** direct native-NOZZLE penetrations")
    add("- Native NOZZLE invariance from r9: **60/60 CATR / POS / ORI "
        "unchanged; 32/32 horizontal NOZZLE blocks fully unchanged**")
    direct_ratios = [item["external_ratio"] for item in direct]
    add("- Top-nozzle adaptation: **28/28 HEIG fields changed only**; "
        "14/14 overwidth nozzle bottoms equal CONE tops within 0.01 mm; "
        f"14/14 direct external ratios are {min(direct_ratios):.1%}–"
        f"{max(direct_ratios):.1%} (minimum required 70%)")
    add("")
    add("| Tag | Type | Elements | Engine source | Motor parts | Drive | Unresolved |")
    add("|-----|------|----------|---------------|-------------|-------|------------|")
    for model, problems in models:
        facts = model.facts
        kind = "MC" if facts["is_mc"] else "non-MC"
        engine_source = facts["engine_source"].replace("engine_shaft_measurements_updated.csv",
                                                       "CSV")
        drive = ("close-coupled" if facts["is_mc"] else
                 f"3 parts ×{facts['shaft_fit_scale']:.4f}")
        add(f"| {model.tag} | {kind} | {len(model.primitives)} | "
            f"{engine_source} | {len(facts['motor_segments'])} | {drive} | "
            f"{len(model.unresolved)} |")
    add("")

    # --- per pump -------------------------------------------------------
    add("## Per-pump record")
    add("")
    for model, problems in models:
        facts = model.facts
        add(f"### {model.tag} — {model.description}")
        add("")
        add(f"- Type: **{'MC pump' if facts['is_mc'] else 'conventional (non-MC)'}**")
        plate = facts["plate"]
        centre = facts["plate_centre"]
        add(f"- Baseplate: {plate[0]:.1f} x {plate[1]:.1f} x {plate[2]:.1f} mm, "
            f"underside centre E {centre[0]:.1f} / N {centre[1]:.1f} / "
            f"U {facts['plate_under']:.1f}  *(location_nozzle_reference)*")
        add(f"- Longitudinal axis: wet end **{facts['wet_end']}**, "
            f"motor end **{facts['motor_end']}**")
        casing = facts.get("casing")
        if casing:
            add(f"- Casing: {casing[0]:.1f} dia x {casing[1]:.1f} long "
                f"*({facts.get('casing_source')})*")
            add(f"- Casing plan basis: {facts.get('casing_plan_basis')}")
        add(f"- Shaft centreline: U {facts.get('shaft_u', 0):.1f} "
            f"*({facts.get('shaft_u_basis')})*")
        add(f"- Engine/shaft source: **{facts['engine_source']}**")
        add(f"- Motor axial envelope: {facts['motor_effective_total']:.1f} mm "
            f"(source total {facts['motor_source_total']:.1f} mm)")
        motor_parts = []
        for item in facts["motor_segments"]:
            if item["kind"] == "CONE":
                size = (f"{item['DBOT']:.1f}→{item['DTOP']:.1f} dia × "
                        f"{item['length']:.1f} long")
            else:
                size = f"{item['DIAM']:.1f} dia × {item['length']:.1f} long"
            motor_parts.append(f"{item['role']} ({item['kind']}, {size})")
        add("- Motor construction, rear/outboard → front/pump side: "
            + "; ".join(motor_parts))
        if "shaft" in facts:
            add(f"- Drive: {facts['shaft']}")
        if facts.get("drive_segments"):
            drive_parts = []
            for item in facts["drive_segments"]:
                if item["kind"] == "CONE":
                    size = (f"{item['diameter_1']:.1f}→"
                            f"{item['diameter_2']:.1f} dia")
                else:
                    size = f"{item['diameter_1']:.1f} dia"
                drive_parts.append(
                    f"{item['role']} ({item['kind']}, {size}, "
                    f"{item['source_length']:.1f} source → {item['length']:.1f} fitted)")
            add("- Drive construction, motor → pump: " + "; ".join(drive_parts))
        top_connection = facts.get("top_nozzle_connections") or []
        if top_connection:
            item = top_connection[0]
            construction = ("lower CYLINDER socket + CONE; native NOZZLE "
                            "starts directly on CONE top"
                            if item["overwidth"] else
                            "direct native NOZZLE penetration; no additive body")
            if item.get("offset_bridge"):
                construction += " plus solid offset casing bridge"
            line = (f"- Top-discharge casing connection: {construction}; nozzle "
                    f"DN {item['nozzle_diameter']:.0f}, casing axial width "
                    f"{item['casing_width']:.1f} mm, fixed flange face "
                    f"U {item['nozzle_face_u']:.1f}, nozzle HEIG "
                    f"{item['nozzle_heig']:.1f} mm, native root "
                    f"U {item['nozzle_root_u']:.1f}")
            if not item["overwidth"]:
                line += f", external ratio {item['external_ratio']:.1%}"
            add(line)
        else:
            add("- Top-discharge casing connection: not applicable (no up nozzle)")
        adjustments = facts.get("nozzle_z_adjustments") or []
        if adjustments:
            add("- Historical source→r9 nozzle flange-face Z resolution "
                "(r12 keeps that face fixed):")
            for item in adjustments:
                add(f"  - {item}")
        else:
            add("- Nozzle Z adjustments: none")
        if model.reference_values:
            add("- Reference Values (assumed, replace when vendor data arrives):")
            for value in sorted(set(model.reference_values)):
                add(f"  - {value}")
        if model.unresolved:
            add("- **Unresolved / conflicting:**")
            for item in model.unresolved:
                add(f"  - {item}")
        if problems:
            add("- **VERIFICATION FAILURES:**")
            for item in problems:
                add(f"  - {item}")
        add("")

    # --- excluded / out of scope ----------------------------------------
    add("## Data-quality exceptions")
    add("")
    add("These are reported explicitly. Source measurements are not overwritten;")
    add("structural adaptations are visible as Reference Values or conflicts.")
    add("")
    add("1. **`204-PU-028` is out of scope.** It carries a casing row "
        "(615 x 140) and an MC casing offset (920 mm), but it does not appear "
        "in `location_nozzle_reference.txt` (the project equipment set) or in "
        "the engine/shaft CSV. Its service name, *POST OXYGEN WASHER DISCHARGE "
        "MC PUMP*, matches no project tag, so it is not a typo for one. Not "
        "modelled.")
    add("2. **Three tags lack a motor/shaft CSV row.** `203-PU-020` uses "
        "`203-PU-031`; `203-PU-026` uses `205-PU-024`; `205-PU-004` uses "
        "`204-PU-006`. The nearest measured non-MC family is selected by plate "
        "length/width and casing diameter, with an axial-occupancy penalty that "
        "rejects donors requiring excessive shaft compression. Axial values "
        "scale with plate length and radial values with plate width. These are "
        "Reference Values, not claimed measurements.")
    add("3. **The three MC rows have shaft fields `N/A`.** No free "
        "`DRIVE_SHAFT` is invented. A structurally continuous close-coupled "
        "lantern spans the motor-to-casing gap.")
    add("4. **Every motor now requires two similar end frustums.** If one end "
        "length is zero/N/A, the measured opposite end supplies the common "
        "length. Both cones taper from the main stator to an outward face at "
        "exactly 2/3 of main diameter. This user instruction overrides "
        "conflicting rear/front diameter fields.")
    add("5. **`205-PU-012` was visibly too short in r7.** r7 compressed its "
        "main barrel to 717.0 mm inside the 997.4 mm source total. r8 retains "
        "997.4 mm as the main barrel, then adds the 129.4 mm rear small barrel "
        "and two 75.5 mm cones outside it, giving a 1277.8 mm motor envelope. "
        "Its free shaft is refitted to the new motor front without changing "
        "source diameters or part ratios.")
    add("6. **r8 still terminated 27 non-MC motor tails with a CYLINDER.** r9 "
        "removes the exterior rear-small cylinder and absorbs its axial "
        "allowance into the main stator, so the rear CONE is the physical tail "
        "on all 30 pumps without shortening any motor envelope. On "
        "`205-PU-012`, the main barrel therefore becomes 1126.8 mm while the "
        "corrected total remains 1277.8 mm.")
    add("7. **MC and zero-side component totals are resolved inside the motor "
        "envelope.** The main barrel absorbs the length correction after both "
        "required cones are inserted; each conflict remains flagged.")
    add("8. **Free-shaft source offsets do not always close both interfaces.** "
        "For each non-MC pump, the three source part ratios are uniformly fitted "
        "from the motor front face to controlled casing engagement. Source "
        "diameters and the two-CYLINDER/one-CONE topology are unchanged; "
        "structure therefore takes priority over a detached literal placement.")
    add("9. **`205-PU-046`, `205-PU-047`, `205-PU-048`** have motor/shaft data "
        "but no casing row, and no same-named casing twin to borrow from. Their "
        "casing sizes are DERIVED from the baseplate and flagged.")
    add("10. **Casing/accepted driver envelope vs suction elevation conflict.** For the pumps "
        "marked *raised* above, the casing diameter in `casing_reference.txt` "
        "or the accepted r6 driver clearance envelope is larger than twice the "
        "available elevation, so a machine centred "
        "on the suction axis would pass through the baseplate and below the "
        "foundation. The shaft/support elevation remains the accepted r6 value; "
        "r7 does not reintroduce a DISH. Nozzle plan positions and directions "
        "remain untouched.")
    add("11. **Twenty-eight pumps have an upward discharge.** r12 divides them "
        "by the verified catalogue DN versus casing axial width. Fourteen nozzles "
        "within that width use no additive connector: the native NOZZLE root "
        "penetrates the crown and 75% remains outside, providing margin over the "
        "required 70%. Fourteen overwidth DN150 openings use a 90%-of-width "
        "lower CYLINDER socket and one concentric CONE. The CONE upper face "
        "equals the native NOZZLE bottom; there is no added upper neck. These "
        "are EQUI primitives, not PIPE/BRANCH items.")
    add("12. **`205-PU-054` has a fixed 308 mm plan offset between its MC casing "
        "centre and fixed up-nozzle centre.** Neither source position is moved. "
        "A casing-owned horizontal CYLINDER basic body overlaps both the volute "
        "and the vertical lower socket so the added construction remains one "
        "solid chain. This is flagged as a Reference Value pending E3D review.")
    add("")
    add("## Verification performed")
    add("")
    add("- The five native skid members replace the rejected duplicate full "
        "baseplate; their combined size and centre match project data for "
        "every pump.")
    add("- All 43 reference members matched one-to-one by source index, kind, "
        "station, rotated ORI, local-axis dimension scale and profile.")
    add("- Reference +E and target transverse direction retain the same "
        "right-handed relationship; every offset PYRAMID leans toward the "
        "machine centreline rather than its mirrored side.")
    add("- Every off-origin hex LOOP was centred on exactly one paired anchor "
        "CYLINDER axis; 10/10 washer/shaft pairs are coaxial per pump.")
    add("- Pump stations were fitted to casing diameter/length; motor stations "
        "were fitted to stator diameter/length and aligned to the actual motor "
        "centre rather than the reference sole-plate centre.")
    add("- All 30 DRIVER groups contain zero DISH primitives and exactly two "
        "end CONEs. The cones have identical lengths and mirrored end "
        "diameters; their small faces point away from the main stator and equal "
        "2/3 of its diameter.")
    add("- Axial ordering is checked independently: the first terminal body at "
        "the motor/outboard end is the rear CONE on all 30 pumps. No CYLINDER "
        "or other motor body exists beyond it.")
    add("- All motor segment chains close to their resolved envelope. "
        "`205-PU-012` is 1277.8 mm; all other tags retain their r7 total span. "
        "Ribs and terminal boxes follow the actual "
        "main stator segment rather than the former full-length cylinder.")
    add("- Every one of the 24 measured non-MC rows plus three derived non-MC "
        "rows has exactly CYLINDER/CYLINDER/CONE in DRIVE_SHAFT. Interfaces are "
        "closed, diameters equal the source/derived record, part ratios are "
        "retained and the pump-side cone grows toward the casing.")
    add("- The three MC pumps have no free DRIVE_SHAFT and retain a continuous "
        "motor-to-casing close-coupled lantern.")
    add("- Canonical r9→r12 comparison keeps all 180 SUBE blocks present. "
        "Only 14 overwidth CASING blocks receive additions: 29 primitive "
        "solids (14 sockets, 14 CONEs and one offset bridge). Their pre-existing "
        "casing elements remain canonical unchanged; "
        "28 top DISCHARGE blocks change only HEIG; all other SUBEs are identical.")
    add("- PYRAMID POS is treated as its geometric centre. The native pump "
        "saddle relationship (top 30/170 of casing radius above the barrel "
        "underside) and motor mounting-pad relationship (top 7/180 of stator "
        "radius above the barrel underside) are retained.")
    add("- All four sole plates bear directly on the target skid top. Each of "
        "the four inner sole gussets spans exactly from its sole-plate top to "
        "its corresponding pump or motor mounting-pad underside.")
    add("- All six outer side/motor stays start exactly on their corresponding "
        "fixed sole-plate top while retaining their machine-relative tops.")
    add("- Every PYRAMID is emitted at the midpoint of its solved bottom/top "
        "faces. The verifier reconstructs its occupied U as POS +/- HEIG/2; "
        "no support reaches below the foundation.")
    add("- The structural BOX/PYRAMID members form one continuous component "
        "back to the five-member skid on all 30 pumps. The graph uses explicit "
        "overlapping end-face bearings, not AABB crossings, and excludes "
        "hardware so a bolt cannot hide a detached support.")
    add("- Hex-head thickness stays at the reference hardware scale; every "
        "anchor starts at the reference-scaled embedment and terminates at "
        "its paired hex-head top.")
    add("- All 60 native NOZZLE blocks were compared directly against r9. "
        "CATR, flange-face POS (including U) and ORI are **60/60 canonical "
        "unchanged**. The 32 horizontal blocks also keep HEIG; the 28 upward "
        "blocks change HEIG only to solve their physical bottom face.")
    add("- Casing diameter and length compared to `casing_reference.txt`.")
    add("- Relational checks: casing/motor coaxiality, connectivity of every "
        "solid back to the baseplate, overwidth socket crown embedment, visible "
        "projection, exact nozzle-bottom/CONE-top terminal closure and smooth "
        "diameter equality at the socket/CONE junction. Direct nozzles are "
        "independently checked to penetrate the crown with at least 70% of "
        "NOZZLE HEIG outside.")
    add("- Every overwidth lower socket fits within the casing axial width. "
        "`205-PU-054` additionally requires one horizontal solid bridge that "
        "overlaps both its casing barrel and vertical socket.")
    add("- Nothing below the foundation datum.")
    add("- Nozzle bore directions recovered geometrically, not read off the "
        "exported `ORI` triad (all 28 discharges share one triad in the source, "
        "so it cannot encode direction).")
    add("- Cooling-rib orientation resolved into axis triads and checked to be "
        "radial, axial and orthonormal: 1080 ribs, 0 wrong.")
    add(f"- The verifier itself was mutation-tested with {MUTATION_COUNT} "
        f"injected defects; all {MUTATION_COUNT} were caught.")
    add("")
    add("**A fresh E3D visual reload is still required before acceptance.** "
        "No claim of E3D success is made here (IR-11d).")
    add("")

    REPORT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {REPORT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
