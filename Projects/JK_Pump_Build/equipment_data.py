def _pump(
    row: int,
    tag: str,
    name: str,
    position: tuple[float, float, float],
    length: float,
    width: float,
    suction: str,
    discharge: str,
    *,
    family: PumpFamily = PumpFamily.STANDARD_HORIZONTAL,
    duty: PumpDuty | None = None,
    top_view: bool = True,
    position_source: Provenance = Provenance.EXCEL,
    longitudinal_axis: str | None = None,
    auxiliary_side: int = 1,
    notes: tuple[str, ...] = (),
) -> PumpSpec:
    if duty is None:
        duty = _classify_duty(name, family)
    source_map = {
        "position": position_source,
        "length": Provenance.EXCEL,
        "width": Provenance.EXCEL,
        "suction_axis": Provenance.EXCEL,
        "discharge_axis": Provenance.EXCEL,
        "longitudinal_axis": (
            Provenance.CLIENT if longitudinal_axis is not None else Provenance.DERIVED
        ),
        "baseplate_thickness": Provenance.CLIENT,
        "pump_family_geometry": Provenance.VENDOR_TYPICAL,
        "duty_classification": Provenance.DERIVED,
        "high_detail_construction": Provenance.VENDOR_TYPICAL,
        "tag_specific_appearance": (
            Provenance.TOP_VIEW if top_view else Provenance.VENDOR_TYPICAL
        ),
        "driver_dimensions": Provenance.STANDARD,
        "nozzle_sizes": Provenance.STANDARD,
        "support_dimensions": Provenance.STANDARD,
    }
    if top_view:
        source_map["top_view_configuration"] = Provenance.TOP_VIEW
    return PumpSpec(
        tag=tag,
        name=name,
        excel_row=row,
        position=position,
        length=length,
        width=width,
        suction_axis=suction,
        discharge_axis=discharge,
        family=family,
        duty=duty,
        appearance=_APPEARANCES[tag],
        longitudinal_axis=longitudinal_axis,
        baseplate_thickness=50.0,
        top_view=f"PU_reference/{tag}.png" if top_view else None,
        auxiliary_side=auxiliary_side,
        sources=source_map,
        notes=notes,
    )


def _classify_duty(name: str, family: PumpFamily) -> PumpDuty:
    """Derive the external construction family from the contractual service name."""
    upper = name.upper()
    if family is PumpFamily.MEDIUM_CONSISTENCY or " MC PUMP" in upper:
        return PumpDuty.MEDIUM_CONSISTENCY
    if "SCREEN FEED" in upper or "SAND SEPARATOR FEED" in upper:
        return PumpDuty.SCREEN_FEED
    if "BOOSTER" in upper:
        return PumpDuty.BOOSTER
    if "WIRE WASH" in upper:
        return PumpDuty.WIRE_WASH
    if "WASHER FEED" in upper:
        return PumpDuty.WASHER_FEED
    if "FILTRATE" in upper:
        return PumpDuty.FILTRATE
    if "SCRUBBER CIRCULATION" in upper:
        return PumpDuty.SCRUBBER_CIRCULATION
    return PumpDuty.DILUTION


