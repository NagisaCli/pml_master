def rounded_route(vertices, radius=50.):
    """Sample native-style 90-degree fillets for an offline path envelope."""
    points = vertices[:-1]
    result = []
    for index, b in enumerate(points):
        a, c = points[index - 1], points[(index + 1) % len(points)]
        before, after = math.dist(a, b), math.dist(b, c)
        assert min(before, after) > 2 * radius
        u = tuple((b[i] - a[i]) / before for i in range(2))
        v = tuple((c[i] - b[i]) / after for i in range(2))
        assert abs(sum(u[i] * v[i] for i in range(2))) < 1e-8
        start = tuple(b[i] - u[i] * radius for i in range(2))
        center = tuple(start[i] + v[i] * radius for i in range(2))
        angle = math.atan2(start[1] - center[1], start[0] - center[0])
        sign = 1 if u[0] * v[1] - u[1] * v[0] > 0 else -1
        for step in range(25):
            theta = angle + sign * math.pi / 2 * step / 24
            result.append((center[0] + radius * math.cos(theta),
                           center[1] + radius * math.sin(theta)))
    return LineString(result + [result[0]])


def write_macro(path, text):
    assert not validate_pml(text), validate_pml(text)
    path.write_bytes(text.replace("\r\n", "\n").replace("\n", "\r\n").encode("ascii"))


def main():
    OUT.mkdir(exist_ok=True)
    assert hashlib.sha256(g.SOURCE.read_bytes()).hexdigest() == g.SOURCE_HASH
    text = g.SOURCE.read_text(encoding="utf-8-sig")
    roots = parse_native_tree(text[text.index("NEW EQUIPMENT"):text.index("\nOLD ")])
    frames = g.index_frames(roots)
    origin = frames[id(roots[0])][0]
    slab = [x for x in roots[0].walk() if x.kind == "EXTRUSION" and x.get("HEIG") == "150mm"][0]
    floor_points = [frames[id(v)][0] for loop in slab.children for v in loop.children if v.kind == "VERTEX"]
    floor = Polygon([(round(p[0] - origin[0], 1), round(p[1] - origin[1], 1)) for p in floor_points])
    candidates = []
    for node in roots[0].children[0].children:
        if node.kind != "EXTRUSION" or node.get("HEIG") != "600mm":
            continue
        points = [frames[id(v)][0] for loop in node.children for v in loop.children if v.kind == "VERTEX"]
        bounds = (min(p[0] - origin[0] for p in points), min(p[1] - origin[1] for p in points),
                  max(p[0] - origin[0] for p in points), max(p[1] - origin[1] for p in points))
        if bounds[0] > floor.bounds[2] + 500 and abs(points[0][2] + 600 - 9700) < .1:
            candidates.append((node, bounds))
    assert len(candidates) == 1
    beam, beam_bounds = candidates[0]
    assert all(abs(a - b) < .1 for a, b in zip(beam_bounds, (12000, 2000, 12600, 8800)))

    baseline = json.loads((g.OUTPUT / "layout_audit.json").read_text(encoding="utf-8"))
    old = [tuple(p) for p in baseline["route_building_xy_mm"]]
    assert len(old) == 37
    i = old.index((10309.98, 8908.))
    assert old[i + 1:i + 4] == [(10309.98, 4278.), (10950., 4278.), (10950., 1308.)]
    # Side returns fit the received beam. The north return uses a 50 mm end
    # inset to pass outside P-EL2-N; applying R1's 150 mm end inset here would
    # intersect that support. This local allowance is explicitly reported.
    outer_e = round(beam_bounds[2] - 150, 2)
    south_n = round(beam_bounds[1] + 150, 1)
    north_n = round(beam_bounds[3] - 50, 1)
    corrected = old[:i + 1] + [(10309.98, north_n), (outer_e, north_n),
                               (outer_e, south_n), (10950., south_n)] + old[i + 3:]
    assert len(corrected) == 39
    old_path, new_path = LineString(old), LineString(corrected)
    assert new_path.is_ring and new_path.is_simple
    changed_window = box(10000., south_n, 12700., north_n)
    before_rest, after_rest = old_path.difference(changed_window), new_path.difference(changed_window)
    assert before_rest.hausdorff_distance(after_rest) < .001
    assert abs(before_rest.length - after_rest.length) < .001

    # The user identifies this as an existing derived/outboard platform.
    # The received export has an outer beam but no separate deck surface here:
    # the planar layout envelope is derived from that beam and the main edge.
    platform = box(floor.bounds[2], beam_bounds[1], beam_bounds[2], beam_bounds[3])
    walking_envelope = unary_union([floor, platform])
    rounded = rounded_route(corrected)
    assert rounded.is_ring and rounded.is_simple
    assert walking_envelope.buffer(.05).covers(rounded.buffer(g.RAIL_RADIUS))
    mouth = LineString([(floor.bounds[2], south_n + 100), (floor.bounds[2], north_n - 100)])
    assert mouth.distance(new_path) > 90
    assert Polygon(new_path).contains(Point(11500, 5500))

    obstacles = [x for x in baseline["all_obstacles"] if x["category"] != "Plate envelope"]
    # Flush embed plates are not above-floor obstructions to the horizontal
    # rail. Their post/base interfaces remain a separate native review item.
    solid_envelopes = unary_union([box(*x["bounds_mm"]) for x in obstacles])
    clearance = rounded.distance(solid_envelopes) - g.RAIL_RADIUS
    assert clearance > 15., clearance
    for entry in baseline["floor_stair_entries"]:
        p = Point(entry["xy_mm"])
        assert Polygon(new_path).contains(p)
        assert p.distance(new_path) >= entry["width_mm"] / 2 + 100

    spec = HandrailSpec(name=f"{PREFIX}/PERIMETER", position=(0., 0., 0.),
                        top_rail_height=1100., mid_rail_height=550., post_spacing=1200.,
                        tangent_offset=0., bend_radius=50., show_kickplate=True,
                        path_items=tuple(RoutePoint((x, y, 0.), 50.) for x, y in corrected))
    block = HandrailBuilder().build(spec)
    full = "\n".join([
        "-- R2: user-corrected exterior platform; outer three sides guarded, inner side open.",
        "-- Fresh load only: select the SAME writable ZONE as /New_washer_biulding.",
        "-- If R1 is already loaded, use the R1_TO_R2 patch instead; do not load both.",
        "-- Source outer beam: local E 12000..12600, N 2000..8800, top U 9700 owner frame.",
        "-- Reference Values: outer/south inset 150; north end inset 50; rail radius 40; fillet 50.",
        "-- Tight north return: provisional section-envelope clearance 17 mm; inspect in E3D.",
        "-- Existing building, access, catalogue and platform geometry are preserved.",
        f"NEW STRU /{PREFIX}",
        "DESC 'R2; outer platform three-side guard; inner access open; offline candidate'",
        "ORI Y IS N AND Z IS U",
        f"POS E {g.fmt(origin[0])}mm N {g.fmt(origin[1])}mm U 9700mm",
        "BUIL false", f"NEW FRMWORK /{PREFIX}/RAILS", "BUIL false", "SHOP false", "",
        block, "END", "END", "",
    ])
    write_macro(OUT / "building_F2_guardrails_R2.txt", full)
    emitted = parse_native_tree(full)
    ef = g.index_frames(emitted)
    recovered = [(ef[id(v)][0][0] - origin[0], ef[id(v)][0][1] - origin[1])
                 for v in emitted[0].walk() if v.kind == "POINTR"]
    assert len(recovered) == 39
    assert LineString(recovered).hausdorff_distance(new_path) < .001

    # In-place, deletion-free patch to the exact R1 emitted in this project.
    # PML1 element navigation is native syntax; receiving-host execution of
    # this patch is pending. Existing attributes and other elements are kept.
    patch = [
        "-- R1 TO R2: run ONCE on the exact original R1 (37 route points).",
        "-- Updates only /DD4060_BUILDING_F2_GUARDRAILS_R1/PERIMETER route points.",
        "-- Keeps all other rail attributes and all building/access elements.",
        "-- Inner rail is relocated to the exterior platform's three open edges.",
        "-- This patch is not needed when loading the complete R2 fresh macro.",
        f"OLD HANDRA {R1_NAME}", "RPATH 1",
    ]
    for index, (x, y) in enumerate(corrected[:37], 1):
        patch.extend([f"POINTR {index}", f"POS E {g.fmt(x)}mm N {g.fmt(y)}mm U 0mm", "END"])
    for x, y in corrected[37:]:
        patch.extend(["NEW POINTR", f"POS E {g.fmt(x)}mm N {g.fmt(y)}mm U 0mm", "FRAD 50mm", "END"])
    patch.extend(["END", "END", ""])
    patch_text = "\n".join(patch)
    write_macro(OUT / "building_F2_guardrails_R1_TO_R2.txt", patch_text)
    simulate_patch(patch_text, old, corrected)

    audit = {
        "status": "OFFLINE_GEOMETRY_PASS_NATIVE_EXECUTION_PENDING",
        "source_sha256": g.SOURCE_HASH,
        "user_correction": "Enclose the derived/exterior platform on its three exposed sides; omit its inner-side railing.",
        "source_external_beam_bounds_local_mm": beam_bounds,
        "derived_platform_layout_envelope_mm": list(platform.bounds),
        "deck_surface": "User-identified existing platform; separate deck slab is not present in the received export; no deck is created.",
        "retained_outside_change_window_mm": list(changed_window.bounds),
        "all_other_R1_segments_unchanged": True,
        "inner_open_span_north_mm": [south_n, north_n],
        "route_points_including_closure": len(corrected),
        "unfilleted_route_length_mm": new_path.length,
        "rail_base_owner_elevation_mm": 9700.,
        "rail_heights_mm": [1100, 550],
        "post_spacing_mm": 1200,
        "minimum_assumed_rail_to_above_floor_section_envelope_mm": clearance,
        "tight_clearance_location": "North return passes outboard of /DD4060-ACCESS-R6/P-EL2-N; source axis plus Reference Value envelope, not a native solid clash check.",
        "reference_values_mm": {"outer_edge_inset": 150, "south_end_inset": 150,
                                "north_end_inset": 50, "rail_envelope_radius": 40,
                                "section_envelope_radius": 125, "fillet_radius": 50},
        "route_building_xy_mm": corrected,
        "patch": {"existing_points_repositioned": 37, "points_appended": 2, "deletions": 0,
                  "receiving_host_execution": "PENDING; requires the exact original R1 with 37 points"},
        "open_acceptance": ["Verify screenshot-to-source exterior-platform identification",
                            "Native patch navigation and full-macro loading",
                            "Actual catalogue clearance, corner posts, embed interfaces and end anchorage",
                            "Platform surface/extent in the live model; source exports only its outboard beam",
                            "Visual acceptance, Save Work and reopen persistence"],
    }
    (OUT / "layout_audit_R2.json").write_text(json.dumps(audit, indent=2) + "\n", encoding="utf-8")
    plot(floor, platform, beam_bounds, baseline, old, corrected)
    assert hashlib.sha256(g.SOURCE.read_bytes()).hexdigest() == g.SOURCE_HASH
    print(json.dumps({k: audit[k] for k in ["status", "source_external_beam_bounds_local_mm",
                     "route_points_including_closure", "unfilleted_route_length_mm",
                     "minimum_assumed_rail_to_above_floor_section_envelope_mm"]}, indent=2))


def simulate_patch(text, old, expected):
    points = list(old)
    active = None
    new = False
    for line in text.splitlines():
        if line.startswith("POINTR "):
            active = int(line.split()[1]) - 1
            assert active < 37
            new = False
        elif line == "NEW POINTR":
            active = len(points)
            points.append(None)
            new = True
        elif line.startswith("POS "):
            value = g.position(line[4:])
            assert value[2] == 0
            points[active] = value[:2]
        elif line == "END":
            active = None
            new = False
    assert points == expected


def plot(floor, platform, beam_bounds, baseline, old, corrected):
    fig, ax = g.plt.subplots(figsize=(13, 7), layout="constrained")
    def patch(poly, **kwargs):
        ax.add_patch(PlotPolygon([(y / 1000, -x / 1000) for x, y in poly.exterior.coords], **kwargs))
    patch(floor, facecolor="#f1f4f7", edgecolor="#67768a", label="Received main slab")
    patch(platform, facecolor="#fff0c2", edgecolor="#c9a341", label="User-identified exterior platform envelope")
    patch(box(*beam_bounds), facecolor="#f4cf76", edgecolor="#b88a2c", alpha=.8, label="Received outer beam")
    for obstacle in baseline["all_obstacles"]:
        if obstacle["category"] == "Concrete column":
            patch(box(*obstacle["bounds_mm"]), facecolor="#85909e", edgecolor="#657080", alpha=.8)
        elif obstacle["category"] == "Access member envelope":
            patch(box(*obstacle["bounds_mm"]), facecolor="#c3c9d0", edgecolor="#7c8797", alpha=.7)
    ax.plot([p[1] / 1000 for p in old], [-p[0] / 1000 for p in old], color="#c04d5b", ls="--", lw=1.7,
            label="R1 path (relocated inside this bay)")
    ax.plot([p[1] / 1000 for p in corrected], [-p[0] / 1000 for p in corrected], color="#0e73c7", lw=2.6,
            label="R2: exterior three-side guardrail")
    ax.annotate("Inner side open\nNo railing across the platform access", xy=(5.5, -11.1), xytext=(2.7, -11.6),
                fontsize=10, color="#276641", arrowprops={"arrowstyle": "->", "color": "#276641"})
    ax.annotate("North return: check native\npost / support clearance", xy=(8.75, -10.99), xytext=(8.95, -11.65),
                fontsize=9, color="#6b4a20", arrowprops={"arrowstyle": "->", "color": "#6b4a20"})
    ax.set(title="DD4060 R2 | Exterior platform guarded on its three exposed sides\nOther R1 segments retained | Offline preview; receiving-host review pending",
           xlabel="Building North (m)", ylabel="Negative East (m)", xlim=(.3, 10.7), ylim=(-13.2, -9.5))
    ax.set_aspect("equal")
    ax.grid(alpha=.15)
    ax.legend(loc="upper center", bbox_to_anchor=(.5, -.17), ncol=3, fontsize=8)
    fig.savefig(OUT / "external_platform_R2.png", dpi=150)
    g.plt.close(fig)


if __name__ == "__main__":
    main()
